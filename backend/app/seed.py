def seed_if_empty():
    db = get_db()
    if db.execute("SELECT COUNT(*) FROM users").fetchone()[0] > 0:
        return

    password_hash = generate_password_hash(DEMO_PASSWORD)
    ids = {}
    for username, full_name, role, mentor_username in USERS:
        mentor_id = ids.get(mentor_username)
        cur = db.execute(
            "INSERT INTO users (username, password_hash, full_name, role, mentor_id) "
            "VALUES (?, ?, ?, ?, ?)",
            (username, password_hash, full_name, role, mentor_id),
        )
        ids[username] = cur.lastrowid

    for position, title, description, tasks in STAGES:
        stage_id = db.execute(
            "INSERT INTO stages (position, title, description) VALUES (?, ?, ?)",
            (position, title, description),
        ).lastrowid
        for task_position, (task_title, link) in enumerate(tasks, start=1):
            db.execute(
                "INSERT INTO tasks (stage_id, position, title, link) VALUES (?, ?, ?, ?)",
                (stage_id, task_position, task_title, link),
            )

    db.executemany(
        "INSERT INTO kb_entries (question, answer, keywords, audience, source) "
        "VALUES (?, ?, ?, ?, 'seed')",
        KB,
    )

    # У Анны уже есть несколько доступов, чтобы было что показать.
    db.executemany(
        "INSERT INTO access_requests (intern_id, system, status) VALUES (?, ?, ?)",
        [
            (ids["intern1"], "GitLab", "granted"),
            (ids["intern1"], "Jira", "requested"),
        ],
    )
    db.commit()
