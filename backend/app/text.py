"""Нормализация текста для поиска по базе знаний.

Слова в нижний регистр, служебные и короткие (<3) отбрасываются,
остальные режутся до 5 букв (грубый стемминг).
"""
import re

STOP = {
    "как", "где", "что", "кто", "чем", "че", "это", "для", "или", "если",
    "не", "на", "по", "из", "за", "от", "до", "при", "про", "без", "под",
    "над", "об", "со", "ко", "во", "и", "а", "но", "да", "же", "ли", "бы",
    "то", "тот", "эта", "эти", "мой", "моя", "мои", "мне", "меня", "ты",
    "вы", "он", "она", "они", "мы", "нам", "нас", "вам", "вас", "его",
    "её", "их", "свой", "своя", "свои", "есть", "быть", "был", "была",
    "были", "будет", "можно", "нужно", "надо", "хочу", "хочет", "есть",
}


def stems(text):
    if not text:
        return set()
    words = re.findall(r"[а-яёa-z0-9]+", text.lower())
    result = set()
    for word in words:
        if len(word) < 3 or word in STOP:
            continue
        result.add(word[:5])
    return result


def signature(text):
    """Порядок-независимый ключ для группировки одинаковых по смыслу вопросов."""
    s = stems(text)
    if not s:
        return (text or "").strip().lower()
    return " ".join(sorted(s))
